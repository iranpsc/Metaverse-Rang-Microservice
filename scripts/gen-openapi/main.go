// Command gen-openapi generates openapi/openapi.yaml from openapi/routes.yaml.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type routesFile struct {
	Routes  []routeDef             `yaml:"routes"`
	Schemas map[string]interface{} `yaml:"schemas,omitempty"`
}

type routeDef struct {
	Path      string                            `yaml:"path"`
	Methods   []string                          `yaml:"methods"`
	Tag       string                            `yaml:"tag"`
	Summary   string                            `yaml:"summary"`
	Security  string                            `yaml:"security"`
	Params    []paramDef                        `yaml:"params,omitempty"`
	Body      map[string]interface{}            `yaml:"body,omitempty"`
	Responses map[string]map[string]interface{} `yaml:"responses,omitempty"`
}

type paramDef struct {
	Name        string      `yaml:"name"`
	In          string      `yaml:"in"`
	Type        string      `yaml:"type"`
	Format      string      `yaml:"format,omitempty"`
	Description string      `yaml:"description,omitempty"`
	Example     interface{} `yaml:"example,omitempty"`
	Required    *bool       `yaml:"required,omitempty"`
}

var pathParamPattern = regexp.MustCompile(`\{([^}]+)\}`)

type openAPISpec struct {
	OpenAPI    string                 `yaml:"openapi"`
	Info       map[string]interface{} `yaml:"info"`
	Servers    []map[string]string    `yaml:"servers"`
	Tags       []map[string]string    `yaml:"tags"`
	Paths      map[string]interface{} `yaml:"paths"`
	Components map[string]interface{} `yaml:"components"`
}

func main() {
	root := findRepoRoot()
	routesPath := filepath.Join(root, "openapi", "routes.yaml")
	outPath := filepath.Join(root, "openapi", "openapi.yaml")
	handlerDir := filepath.Join(root, "services", "support-service", "internal", "handler")

	data, err := os.ReadFile(routesPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read routes: %v\n", err)
		os.Exit(1)
	}

	var routes routesFile
	if err := yaml.Unmarshal(data, &routes); err != nil {
		fmt.Fprintf(os.Stderr, "parse routes: %v\n", err)
		os.Exit(1)
	}

	discovered := map[string]discoveredEndpoint{}
	if _, err := os.Stat(handlerDir); err == nil {
		discovered, err = discoverHandlerEndpoints(handlerDir)
		if err != nil {
			fmt.Fprintf(os.Stderr, "discover handler params: %v\n", err)
			os.Exit(1)
		}
	}

	augmentedRoutes := augmentRoutesFromDiscovery(routes.Routes, discovered)
	appURL := loadAppURL(root)
	spec := buildSpec(augmentedRoutes, discovered, appURL, routes.Schemas)
	out, err := yaml.Marshal(spec)
	if err != nil {
		fmt.Fprintf(os.Stderr, "marshal spec: %v\n", err)
		os.Exit(1)
	}

	header := "# Generated by scripts/gen-openapi — do not edit by hand.\n# Sources: openapi/routes.yaml + service HTTP handler discovery — regenerate with: make openapi\n\n"
	if err := os.WriteFile(outPath, append([]byte(header), out...), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write spec: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s (%d routes, %d discovered endpoints)\n", outPath, len(augmentedRoutes), len(discovered))
}

func findRepoRoot() string {
	if wd, err := os.Getwd(); err == nil {
		dir := wd
		for i := 0; i < 6; i++ {
			if _, err := os.Stat(filepath.Join(dir, "openapi", "routes.yaml")); err == nil {
				return dir
			}
			parent := filepath.Dir(dir)
			if parent == dir {
				break
			}
			dir = parent
		}
	}
	return "."
}

func loadAppURL(root string) string {
	if v := strings.TrimSpace(os.Getenv("APP_URL")); v != "" {
		return strings.TrimSuffix(v, "/")
	}

	envPath := filepath.Join(root, ".env")
	data, err := os.ReadFile(envPath)
	if err != nil {
		return "http://localhost:8000"
	}

	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok || strings.TrimSpace(key) != "APP_URL" {
			continue
		}
		value = strings.TrimSpace(value)
		value = strings.Trim(value, `"'`)
		if value != "" {
			return strings.TrimSuffix(value, "/")
		}
	}

	return "http://localhost:8000"
}

func buildServers(appURL string) []map[string]string {
	description := "API Gateway"
	if appURL == "http://localhost:8000" {
		description = "Kong API Gateway (local)"
	}

	servers := []map[string]string{
		{"url": appURL, "description": description},
	}
	if appURL == "http://localhost:8000" {
		servers = append(servers, map[string]string{
			"url":         "http://localhost:8070",
			"description": "support-service HTTP direct (dev)",
		})
	}
	return servers
}

func buildSpec(routes []routeDef, discovered map[string]discoveredEndpoint, appURL string, schemas map[string]interface{}) openAPISpec {
	tagSet := map[string]struct{}{}
	paths := map[string]interface{}{}

	for _, route := range routes {
		tagSet[route.Tag] = struct{}{}
		pathItem, ok := paths[route.Path].(map[string]interface{})
		if !ok {
			pathItem = map[string]interface{}{}
			paths[route.Path] = pathItem
		}

		for _, method := range route.Methods {
			op := map[string]interface{}{
				"tags":        []string{route.Tag},
				"summary":     route.Summary,
				"operationId": operationID(route.Path, method),
				"responses":   buildResponses(route),
			}

			if params := buildParameters(route, method, discovered); len(params) > 0 {
				op["parameters"] = params
			}

			if sec := securityRequirement(route.Security); sec != nil {
				op["security"] = sec
			}

			if methodNeedsBody(method) {
				op["requestBody"] = buildRequestBody(route.Body)
			}

			pathItem[strings.ToLower(method)] = op
		}
	}

	tags := make([]map[string]string, 0, len(tagSet))
	for tag := range tagSet {
		tags = append(tags, map[string]string{"name": tag})
	}
	sort.Slice(tags, func(i, j int) bool {
		return tags[i]["name"] < tags[j]["name"]
	})

	spec := openAPISpec{
		OpenAPI: "3.0.3",
		Info: map[string]interface{}{
			"title":       "metarang API",
			"description": "REST API for metarang microservices. Legacy-compatible JSON responses served via Kong → service HTTP APIs.",
			"version":     "1.0.0",
			"contact": map[string]string{
				"name": "metarang",
			},
		},
		Servers: buildServers(appURL),
		Tags:    tags,
		Paths:   paths,
		Components: map[string]interface{}{
			"securitySchemes": map[string]interface{}{
				"BearerAuth": map[string]interface{}{
					"type":         "http",
					"scheme":       "bearer",
					"bearerFormat": "Token",
					"description":  "Bearer token. Header: Authorization: Bearer {token}",
				},
			},
			"schemas": map[string]interface{}{
				"Error": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"message": map[string]string{"type": "string"},
					},
				},
				"ValidationError": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"message": map[string]string{"type": "string"},
						"errors": map[string]interface{}{
							"type": "object",
							"additionalProperties": map[string]interface{}{
								"type":  "array",
								"items": map[string]string{"type": "string"},
							},
						},
					},
				},
				"ApiError": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"error": map[string]interface{}{
							"type":        "string",
							"description": "Human-readable error message",
						},
					},
				},
				"LockedAccount": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"message": map[string]interface{}{
							"type":    "string",
							"example": "Account security is locked. Unlock your account security to continue.",
						},
					},
				},
				"PaginationLinks": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"first": map[string]interface{}{"type": "string", "nullable": true},
						"last":  map[string]interface{}{"type": "string", "nullable": true},
						"prev":  map[string]interface{}{"type": "string", "nullable": true},
						"next":  map[string]interface{}{"type": "string", "nullable": true},
					},
				},
				"PaginationMeta": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"current_page": map[string]interface{}{"type": "integer", "example": 1},
						"from":         map[string]interface{}{"type": "integer", "nullable": true, "example": 1},
						"last_page":    map[string]interface{}{"type": "integer", "example": 1},
						"path":         map[string]interface{}{"type": "string"},
						"per_page":     map[string]interface{}{"type": "integer", "example": 10},
						"to":           map[string]interface{}{"type": "integer", "nullable": true, "example": 10},
						"total":        map[string]interface{}{"type": "integer", "example": 0},
					},
				},
				"ObjectValidationError": map[string]interface{}{
					"type": "object",
					"properties": map[string]interface{}{
						"message": map[string]interface{}{
							"type":        "string",
							"description": "Text to show the user",
						},
						"errors": map[string]interface{}{
							"type":        "object",
							"description": "Field messages. Empty when the error is not tied to one field.",
							"additionalProperties": map[string]interface{}{
								"type": "string",
							},
						},
					},
				},
			},
		},
	}
	componentSchemas := spec.Components["schemas"].(map[string]interface{})
	for name, schema := range schemas {
		componentSchemas[name] = schema
	}
	return spec
}

func buildResponses(route routeDef) map[string]interface{} {
	responses := map[string]interface{}{
		"200": map[string]interface{}{
			"description": "Successful response",
		},
		"401": map[string]interface{}{
			"description": "Unauthenticated",
			"content": map[string]interface{}{
				"application/json": map[string]interface{}{
					"schema": map[string]string{"$ref": "#/components/schemas/Error"},
				},
			},
		},
		"422": map[string]interface{}{
			"description": "Validation error",
			"content": map[string]interface{}{
				"application/json": map[string]interface{}{
					"schema": map[string]string{"$ref": "#/components/schemas/ValidationError"},
				},
			},
		},
	}

	for code, response := range route.Responses {
		responses[code] = response
	}

	return responses
}

func securityRequirement(security string) []map[string][]string {
	switch security {
	case "bearer", "verified_email":
		return []map[string][]string{{"BearerAuth": {}}}
	case "optional", "guest":
		return []map[string][]string{
			{},
			{"BearerAuth": {}},
		}
	default:
		return nil
	}
}

// buildRequestBody turns a route `body` into an OpenAPI requestBody.
// A body with a `schema` key is a wrapper: `required` (bool) says whether the
// body itself is required, and `schema` is the JSON schema. Any other body map
// is the schema, and the body is required.
func buildRequestBody(body map[string]interface{}) map[string]interface{} {
	schema, required, description := resolveRequestBody(body)
	content := map[string]interface{}{
		"application/json": map[string]interface{}{
			"schema": schema,
		},
		"multipart/form-data": map[string]interface{}{
			"schema": schema,
		},
	}
	request := map[string]interface{}{
		"required": required,
		"content":  content,
	}
	if description != "" {
		request["description"] = description
	}
	return request
}

func resolveRequestBody(body map[string]interface{}) (schema interface{}, required bool, description string) {
	required = true
	if len(body) == 0 {
		return map[string]interface{}{"type": "object"}, true, ""
	}
	rawSchema, hasSchema := body["schema"]
	if !hasSchema {
		return body, true, ""
	}
	if flag, ok := body["required"].(bool); ok {
		required = flag
	}
	if desc, ok := body["description"].(string); ok {
		description = desc
	}
	return rawSchema, required, description
}

func methodNeedsBody(method string) bool {
	switch strings.ToLower(method) {
	case "post", "put", "patch":
		return true
	default:
		return false
	}
}

func operationID(path, method string) string {
	slug := strings.TrimPrefix(path, "/api/")
	slug = strings.ReplaceAll(slug, "/", "_")
	slug = strings.ReplaceAll(slug, "{", "")
	slug = strings.ReplaceAll(slug, "}", "")
	return fmt.Sprintf("%s_%s", strings.ToLower(method), slug)
}

func buildParameters(route routeDef, method string, discovered map[string]discoveredEndpoint) []map[string]interface{} {
	overrides := map[string]paramDef{}
	for _, p := range route.Params {
		overrides[p.Name] = p
	}

	var pathParamDefs []paramDef
	var queryParamDefs []paramDef
	if ep, ok := lookupDiscovered(discovered, method, route.Path); ok {
		pathParamDefs = ep.PathParams
		queryParamDefs = ep.QueryParams
	}

	pathParams := mergeDiscoveredPathParams(route.Path, pathParamDefs, overrides)
	queryParams := mergeParamDefs(nil, queryParamDefs)
	for _, p := range route.Params {
		if p.In == "query" {
			queryParams = mergeParamDefs(queryParams, []paramDef{p})
		}
	}

	params := make([]map[string]interface{}, 0, len(pathParams)+len(queryParams))
	for _, p := range pathParams {
		if override, ok := overrides[p.Name]; ok && (override.In == "" || override.In == "path") {
			params = append(params, openAPIParameter(mergeParamDefs([]paramDef{p}, []paramDef{override})[0]))
			continue
		}
		params = append(params, openAPIParameter(p))
	}
	for _, p := range queryParams {
		params = append(params, openAPIParameter(p))
	}

	return params
}

func openAPIParameter(p paramDef) map[string]interface{} {
	in := p.In
	if in == "" {
		in = "query"
	}
	paramType := p.Type
	if paramType == "" {
		if in == "path" {
			paramType = inferPathParamType(p.Name)
		} else {
			paramType = inferQueryParamType(p.Name)
		}
	}

	schema := map[string]interface{}{"type": paramType}
	if p.Format != "" {
		schema["format"] = p.Format
	}
	if p.Example != nil {
		schema["example"] = p.Example
	} else if in == "path" {
		_, format, example := inferParamSchema(p.Name)
		if format != "" {
			schema["format"] = format
		}
		if example != nil {
			schema["example"] = example
		}
	}
	if paramType == "array" {
		schema["items"] = map[string]string{"type": "string"}
	}

	required := in == "path"
	if p.Required != nil {
		required = *p.Required
	}

	description := p.Description
	if description == "" && in == "path" {
		description = pathParamDescription(p.Name)
	}
	if description == "" && in == "query" {
		description = queryParamDescription(p.Name)
	}

	return map[string]interface{}{
		"name":        p.Name,
		"in":          in,
		"required":    required,
		"description": description,
		"schema":      schema,
	}
}

func augmentRoutesFromDiscovery(routes []routeDef, discovered map[string]discoveredEndpoint) []routeDef {
	known := map[string]struct{}{}
	for _, route := range routes {
		for _, method := range route.Methods {
			known[endpointKey(method, route.Path)] = struct{}{}
		}
	}

	augmented := append([]routeDef{}, routes...)
	keys := make([]string, 0, len(discovered))
	for key := range discovered {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	for _, key := range keys {
		if _, ok := known[key]; ok {
			continue
		}
		ep := discovered[key]
		augmented = append(augmented, routeDef{
			Path:     ep.Path,
			Methods:  []string{strings.ToLower(ep.Method)},
			Tag:      inferTagFromPath(ep.Path),
			Summary:  ep.Summary,
			Security: inferSecurityFromPath(ep.Path),
		})
	}

	return augmented
}

func inferTagFromPath(path string) string {
	trimmed := strings.TrimPrefix(path, "/api/")
	parts := strings.Split(trimmed, "/")
	if len(parts) == 0 || parts[0] == "" {
		return "API"
	}
	segment := parts[0]
	words := strings.Fields(strings.NewReplacer("-", " ", "_", " ").Replace(segment))
	for i, word := range words {
		if len(word) == 0 {
			continue
		}
		words[i] = strings.ToUpper(word[:1]) + word[1:]
	}
	return strings.Join(words, " ")
}

func inferSecurityFromPath(path string) string {
	publicPrefixes := []string{
		"/api/auth/callback",
		"/api/auth/validate",
		"/api/citizen/",
		"/api/order/callback",
		"/api/upload",
		"/api/levels",
		"/api/maps",
		"/api/tutorials",
		"/api/video-tutorials",
		"/api/calendar",
		"/api/features",
		"/api/store",
	}
	for _, prefix := range publicPrefixes {
		if strings.HasPrefix(path, prefix) {
			return "optional"
		}
	}
	if strings.HasPrefix(path, "/api/auth/register") || strings.HasPrefix(path, "/api/auth/redirect") {
		return "guest"
	}
	return "bearer"
}

